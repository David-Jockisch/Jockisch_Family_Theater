#!/usr/bin/env node
"use strict";

const fs = require("fs");
const path = require("path");

const PROJECT_ROOT = path.resolve(__dirname, "..", "..");

function getArg(name) {
  const prefix = `--${name}=`;
  const match = process.argv.find((arg) => arg.startsWith(prefix));
  return match ? match.slice(prefix.length) : null;
}

const libraryArg = getArg("library");
const outputArg = getArg("output");
const dryRun = process.argv.includes("--dry-run");

const MOVIE_LIBRARY_PATH = path.resolve(
  PROJECT_ROOT,
  libraryArg || path.join("library", "movies", "movie-library.js")
);

const RATINGS_ROOT = path.resolve(
  PROJECT_ROOT,
  outputArg || path.join("library", "ratings")
);

const MOVIES_DIR = path.join(RATINGS_ROOT, "movies");
const INDEX_PATH = path.join(RATINGS_ROOT, "index.js");

function fail(message) {
  console.error(`\n❌ ${message}\n`);
  process.exit(1);
}

function quote(value) {
  return JSON.stringify(value ?? "");
}

function loadMovieLibrary(filePath) {
  if (!fs.existsSync(filePath)) {
    fail(
      `Movie library not found:\n${filePath}\n\n` +
        "Run this from the project root, or use:\n" +
        "node tools/ratings/generate-rating-files.js --library=path/to/movie-library.js"
    );
  }

  const resolved = require.resolve(filePath);
  delete require.cache[resolved];

  let library;
  try {
    library = require(resolved);
  } catch (error) {
    fail(`Could not load movie library:\n${error.message}`);
  }

  if (!Array.isArray(library)) {
    fail("movie-library.js must export an array using module.exports = movieLibrary;");
  }

  return library.filter(
    (movie) =>
      movie &&
      typeof movie === "object" &&
      movie.id &&
      movie.type !== "games-library" &&
      movie.id !== "games-library"
  );
}

function validateMovies(movies) {
  const seen = new Set();
  const duplicates = new Set();

  for (const movie of movies) {
    if (seen.has(movie.id)) duplicates.add(movie.id);
    seen.add(movie.id);
  }

  if (duplicates.size) {
    fail(`Duplicate movie IDs found: ${[...duplicates].sort().join(", ")}`);
  }
}

function buildStarterFile(movie) {
  const fields = [
    ["id", movie.id],
    ["title", movie.title],
    ["collection", movie.collection],
    ["franchise", movie.franchise],
    ["boothGroup", movie.boothGroup],
    ["edition", movie.edition],
    ["year", movie.year],
    ["rating", movie.rating],
    ["runtime", movie.runtime]
  ].filter(([, value]) => value !== undefined && value !== null && value !== "");

  const body = fields
    .map(([key, value]) => `  ${key}: ${quote(value)}`)
    .join(",\n");

  return `// JFT Movie Guide starter file\n// Add review fields below the library metadata as this guide is completed.\n\nmodule.exports = {\n${body}\n};\n`;
}

function buildIndex(movies) {
  const sorted = [...movies].sort((a, b) => a.id.localeCompare(b.id));

  const imports = sorted
    .map((movie) => {
      const variable = movie.id.replace(/[^a-zA-Z0-9]+(.)?/g, (_, char) =>
        char ? char.toUpperCase() : ""
      );
      const safeVariable = /^\d/.test(variable) ? `movie${variable}` : variable;
      return {
        id: movie.id,
        variable: safeVariable || "movieReview"
      };
    });

  const requireLines = imports
    .map(({ id, variable }) => `const ${variable} = require("./movies/${id}.js");`)
    .join("\n");

  const arrayLines = imports.map(({ variable }) => `  ${variable}`).join(",\n");

  return `// AUTO-GENERATED by tools/ratings/generate-rating-files.js\n// Do not edit this file manually. Run the generator after adding movies.\n\n${requireLines}\n\nconst movieRatings = [\n${arrayLines}\n];\n\nfunction getMovieRating(movieId) {\n  return movieRatings.find((review) => review.id === movieId) || null;\n}\n\nmodule.exports = {\n  movieRatings,\n  getMovieRating\n};\n`;
}

function writeFileSafely(filePath, contents, overwrite = false) {
  if (!overwrite && fs.existsSync(filePath)) return false;
  if (!dryRun) fs.writeFileSync(filePath, contents, "utf8");
  return true;
}

function main() {
  const movies = loadMovieLibrary(MOVIE_LIBRARY_PATH);
  validateMovies(movies);

  if (!dryRun) fs.mkdirSync(MOVIES_DIR, { recursive: true });

  let created = 0;
  let skipped = 0;

  for (const movie of [...movies].sort((a, b) => a.id.localeCompare(b.id))) {
    const target = path.join(MOVIES_DIR, `${movie.id}.js`);
    const didCreate = writeFileSafely(target, buildStarterFile(movie), false);

    if (didCreate) {
      created += 1;
      console.log(`${dryRun ? "Would create" : "Created"}: ${path.relative(PROJECT_ROOT, target)}`);
    } else {
      skipped += 1;
    }
  }

  const indexContents = buildIndex(movies);
  if (!dryRun) {
    fs.mkdirSync(RATINGS_ROOT, { recursive: true });
    fs.writeFileSync(INDEX_PATH, indexContents, "utf8");
  }

  console.log("\n🎬 JFT Rating File Generator");
  console.log(`Movies found: ${movies.length}`);
  console.log(`${dryRun ? "Would create" : "Created"}: ${created}`);
  console.log(`Skipped existing: ${skipped}`);
  console.log(`${dryRun ? "Would update" : "Updated"}: ${path.relative(PROJECT_ROOT, INDEX_PATH)}`);
  if (dryRun) console.log("Dry run only — no files were changed.");
  console.log("");
}

main();
